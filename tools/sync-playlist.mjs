#!/usr/bin/env node
/**
 * Premer Gaan - playlist sync
 * ---------------------------
 * Scans songs/ and reconciles songs.js with what's actually on disk:
 *
 *   - new .mp3 in songs/  -> new entry appended, title prettified from the
 *                           filename, artist + cover art looked up on the
 *                           iTunes Store and downloaded into covers/
 *   - entry with no file  -> removed (it would just be a dead row)
 *   - existing entries    -> left completely alone, including their order
 *
 * The same script runs on this PC and inside the sync-playlist GitHub Action,
 * so the playlist is built the same way in both places.
 *
 * Usage:
 *   node tools/sync-playlist.mjs              # sync, fetch artwork
 *   node tools/sync-playlist.mjs --dry-run    # report only, write nothing
 *   node tools/sync-playlist.mjs --no-art     # sync but skip iTunes lookups
 *   node tools/sync-playlist.mjs --keep-missing  # don't drop entries without files
 */

import { readFile, writeFile, readdir, mkdir, access } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SONGS_DIR = path.join(ROOT, "songs");
const COVERS_DIR = path.join(ROOT, "covers");
const SONGS_JS = path.join(ROOT, "songs.js");

const argv = process.argv.slice(2);
const DRY_RUN = argv.includes("--dry-run");
const NO_ART = argv.includes("--no-art");
const KEEP_MISSING = argv.includes("--keep-missing");

const HEADER = `// ============================================================
//  Premer Gaan - songs
//
//  This file is the single source of truth for the playlist.
//  file : uniquely-named audio in /songs (unique names also bust
//         any cached copies on hosting/CDN).
//  cover: local artwork in /covers, downloaded from the iTunes Store.
//         Delete the cover field to fall back to searching iTunes
//         by artist + title at runtime.
//
//  AUTO-GENERATED by tools/sync-playlist.mjs - drop an mp3 into
//  /songs and re-run the script (or push, if the GitHub Action is
//  enabled) to add it to the playlist.
// ============================================================`;

const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "track";

// "ke_tui_ey_bol" / "ke-tui-ey-bol" / "ke tui ey bol" -> "Ke Tui Ey Bol"
const prettify = (s) =>
  s
    .replace(/\.[a-z0-9]+$/i, "")
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b[a-z]/g, (c) => c.toUpperCase());

async function exists(p) {
  try {
    await access(p);
    return true;
  } catch {
    return false;
  }
}

// ---------- read the current playlist ----------

async function readEntries() {
  const src = await readFile(SONGS_JS, "utf8");
  const body = src.slice(src.indexOf("var SONGS = ["));
  const entries = [];
  const re = /\{\s*title:\s*"((?:[^"\\]|\\.)*)"\s*,\s*artist:\s*"((?:[^"\\]|\\.)*)"\s*,\s*file:\s*"((?:[^"\\]|\\.)*)"(?:\s*,\s*cover:\s*"((?:[^"\\]|\\.)*)")?\s*,?\s*\}/g;
  let m;
  while ((m = re.exec(body)) !== null) {
    entries.push({
      title: m[1],
      artist: m[2],
      file: m[3],
      cover: m[4] || undefined,
    });
  }
  return { src, entries };
}

// ---------- iTunes lookup ----------

async function itunes(term) {
  const url =
    "https://itunes.apple.com/search?term=" +
    encodeURIComponent(term) +
    "&media=music&entity=musicTrack&limit=1";
  try {
    const res = await fetch(url, {
      headers: { "User-Agent": "premer-gaan-sync" },
      signal: AbortSignal.timeout(25000),
    });
    if (!res.ok) return null;
    const data = await res.json();
    return data.results && data.results[0] ? data.results[0] : null;
  } catch {
    return null;
  }
}

async function downloadArtwork(url, dest) {
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(40000) });
    if (!res.ok) return false;
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length < 1000) return false;
    await writeFile(dest, buf);
    return true;
  } catch {
    return false;
  }
}

/** Try a handful of search shapes, keep the first real hit. */
async function findTrack(title) {
  const attempts = [title, `${title} bengali song`, title.replace(/[^a-z0-9 ]/gi, "")];
  for (const term of attempts) {
    if (!term.trim()) continue;
    const hit = await itunes(term);
    if (hit && hit.trackName) return hit;
    await new Promise((r) => setTimeout(r, 250));
  }
  return null;
}

// ---------- main ----------

async function main() {
  await mkdir(COVERS_DIR, { recursive: true });

  const files = (await readdir(SONGS_DIR))
    .filter((f) => /\.mp3$/i.test(f))
    .sort();

  const { entries } = await readEntries();
  const byFile = new Map(entries.map((e) => [e.file, e]));
  const known = new Set(byFile.keys());

  const log = (...a) => console.log(...a);
  log(`songs/ has ${files.length} mp3 file(s); songs.js has ${entries.length} entry/entries\n`);

  const kept = [];
  const added = [];
  const dropped = [];

  // keep existing entries, in their existing order
  for (const e of entries) {
    if (known.has(e.file) && files.includes(path.basename(e.file))) {
      kept.push(e);
    } else if (KEEP_MISSING) {
      kept.push(e);
    } else {
      dropped.push(e);
    }
  }

  // add whatever is on disk but not in the playlist
  const newFiles = files.filter((f) => !known.has("songs/" + f));
  const takenTitles = new Set(kept.map((e) => e.title.toLowerCase()));

  for (const f of newFiles) {
    const base = path.basename(f, path.extname(f));
    let title = prettify(base);
    if (takenTitles.has(title.toLowerCase())) {
      const alt = `${title} (${path.extname(f).slice(1)})`;
      title = alt;
    }
    takenTitles.add(title.toLowerCase());

    const entry = { title, artist: "", file: "songs/" + f };
    log(`  + NEW  ${f}`);
    log(`        title  -> "${title}"`);

    if (!NO_ART) {
      const hit = await findTrack(title);
      if (hit) {
        entry.artist = hit.artistName || "";
        const slug = slugify(title);
        const dest = path.join(COVERS_DIR, `${slug}.jpg`);
        if (await downloadArtwork((hit.artworkUrl100 || "").replace(/100x100bb/, "600x600bb"), dest)) {
          entry.cover = `covers/${slug}.jpg`;
          log(`        artist -> "${entry.artist}"`);
          log(`        cover  -> ${entry.cover}  (from "${hit.trackName}")`);
        } else {
          log(`        artist -> "${entry.artist}"  (artwork download failed)`);
        }
      } else {
        log(`        no iTunes match - add the artist by hand in songs.js`);
      }
      await new Promise((r) => setTimeout(r, 250));
    }
    added.push(entry);
  }

  // new tracks go to the end, alphabetically, so the existing order is stable
  added.sort((a, b) => a.title.localeCompare(b.title));
  const final = [...kept, ...added];

  if (dropped.length) {
    log("");
    for (const e of dropped) log(`  - DROP ${e.file}  (file not in songs/)`);
  }

  const body =
    HEADER +
    "\n\nvar SONGS = [\n" +
    final
      .map(
        (e) =>
          `  { title: "${e.title}", artist: "${e.artist}", file: "${e.file}"` +
          (e.cover ? `, cover: "${e.cover}"` : "") +
          " },"
      )
      .join("\n") +
    "\n];\n";

  const unchanged =
    final.length === entries.length &&
    final.every((e, i) => {
      const o = entries[i];
      return (
        o &&
        o.title === e.title &&
        o.artist === e.artist &&
        o.file === e.file &&
        (o.cover || "") === (e.cover || "")
      );
    }) &&
    dropped.length === 0 &&
    added.length === 0;

  if (unchanged) {
    log("\nPlaylist already in sync - songs.js unchanged.");
    return;
  }

  if (DRY_RUN) {
    log("\n[dry run] songs.js would be rewritten with:");
    final.forEach((e, i) => log(`  ${String(i + 1).padStart(2)}. ${e.title} - ${e.artist || "(no artist)"}`));
    return;
  }

  await writeFile(SONGS_JS, body, "utf8");
  log(`\nsongs.js updated: ${kept.length} kept, ${added.length} added, ${dropped.length} dropped, ${final.length} total.`);
}

main().catch((err) => {
  console.error("sync-playlist failed:", err);
  process.exit(1);
});
